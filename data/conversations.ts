import { readingFromFurigana, stripFurigana } from "@/lib/japanese/furigana";
import type {
  Conversation,
  ConversationLine,
  Difficulty,
  JlptLevel,
  Speaker,
} from "@/types/content";

/**
 * Natürliche Alltagsdialoge. Jede Zeile ist mit Vokabeln und Grammatik verknüpft.
 * Übersetzungen geben wieder, was man im Deutschen in derselben Situation sagen würde.
 */

type Line = [
  speaker: string,
  notation: string,
  romaji: string,
  german: string,
  vocabularyIds?: string[],
  grammarIds?: string[],
  noteDe?: string,
];

type Definition = {
  id: string;
  situationId: string;
  title: string;
  titleDe: string;
  difficulty: Difficulty;
  jlptEstimate?: JlptLevel;
  register: Conversation["register"];
  descriptionDe: string;
  speakers: Speaker[];
  lines: Line[];
};

const learner = (nameDe = "Du", nameJa = "あなた"): Speaker => ({
  key: "me",
  nameDe,
  nameJa,
  isLearner: true,
});
const role = (key: string, nameDe: string, nameJa: string): Speaker => ({
  key,
  nameDe,
  nameJa,
  isLearner: false,
});

function conversation(def: Definition): Conversation {
  const lines: ConversationLine[] = def.lines.map(
    ([speaker, notation, romaji, german, vocabularyIds = [], grammarIds = [], noteDe], index) => {
      const japanese = stripFurigana(notation);
      return {
        id: `${def.id}-${index + 1}`,
        conversationId: def.id,
        speaker,
        position: index + 1,
        japanese,
        furigana: japanese !== notation ? notation : undefined,
        reading: readingFromFurigana(notation),
        romaji,
        german,
        noteDe,
        vocabularyIds,
        grammarIds,
      };
    },
  );
  return {
    id: def.id,
    titleJa: stripFurigana(def.title),
    titleReading: readingFromFurigana(def.title),
    titleDe: def.titleDe,
    situationId: def.situationId,
    difficulty: def.difficulty,
    jlptEstimate: def.jlptEstimate,
    register: def.register,
    descriptionDe: def.descriptionDe,
    speakers: def.speakers,
    lines,
  };
}

