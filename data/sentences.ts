import { readingFromFurigana, stripFurigana } from "@/lib/japanese/furigana";
import type { Sentence } from "@/types/content";

/**
 * Beispielsätze aus typischen Alltagssituationen. Übersetzungen sind kontextbezogen
 * und natürlich formuliert, nicht wörtlich. Japanisch und Lesung kommen aus der Notation.
 */

function s(
  id: string,
  notation: string,
  romaji: string,
  german: string,
  vocabularyIds: string[],
  grammarIds: string[],
  contextDe?: string,
): Sentence {
  const japanese = stripFurigana(notation);
  return {
    id,
    japanese,
    furigana: japanese !== notation ? notation : undefined,
    reading: readingFromFurigana(notation),
    romaji,
    german,
    contextDe,
    vocabularyIds,
    grammarIds,
  };
}

